/// The real, live `GET /gate/validators` and `GET /gate/stats`
/// fetchers (`DEC-193`, product rebuild Block E). Matches
/// `agents_api.dart`'s own established, injected-function pattern
/// exactly.
library;

import 'dart:convert';

import 'package:http/http.dart' as http;

import 'package:quorum_mobile/api/api_exceptions.dart';
import 'package:quorum_mobile/config/api_config.dart';
import 'package:quorum_mobile/features/gate_showcase/gate_showcase_logic.dart';

typedef GateValidatorsFetcher = Future<List<GateValidatorData>> Function();
typedef GateStatsFetcher = Future<GateStatsData> Function();

GateValidatorsFetcher createGateValidatorsFetcher({
  required Future<String?> Function() getAccessToken,
  required http.Client client,
  String baseUrl = ApiConfig.baseUrl,
}) {
  return () async {
    final accessToken = await getAccessToken();
    if (accessToken == null) {
      throw const ApiException('Your session has expired -- please sign in again.', statusCode: 401);
    }

    final http.Response response;
    try {
      response = await client.get(
        Uri.parse('$baseUrl/gate/validators'),
        headers: {'Authorization': 'Bearer $accessToken'},
      );
    } catch (e) {
      throw const ApiException('Could not reach Quorum -- check your connection and try again.');
    }

    if (response.statusCode == 401) {
      throw const ApiException('Your session has expired -- please sign in again.', statusCode: 401);
    }
    if (response.statusCode != 200) {
      throw ApiException('Could not load the Gate validator roster right now.', statusCode: response.statusCode);
    }

    final Map<String, dynamic> json;
    try {
      json = jsonDecode(response.body) as Map<String, dynamic>;
    } catch (e) {
      throw const ApiException('Quorum sent back something this app could not understand.');
    }

    final rawValidators = json['validators'] as List<dynamic>;
    return rawValidators.map((raw) => GateValidatorData.fromJson(raw as Map<String, dynamic>)).toList();
  };
}

